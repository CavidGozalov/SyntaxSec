-- The past dates on offer (newest first, at most 60) with the caller's status.
create or replace function public.get_daily_archive()
returns jsonb
language plpgsql stable security definer set search_path = public, pg_temp
as $$
declare
  v_user  uuid := auth.uid();
  v_today date := public.daily_today();
  v_start date;
  v_list  jsonb;
begin
  if v_user is null then
    raise exception 'not_authenticated' using errcode = 'P0001';
  end if;
  select archive_start into v_start from public.progression_settings limit 1;

  select coalesce(jsonb_agg(jsonb_build_object(
           'date', v_today - g.i,
           'answered', a.user_id is not null,
           'is_correct', a.is_correct
         ) order by g.i), '[]'::jsonb)
    into v_list
  from generate_series(1, least(60, v_today - v_start)) as g(i)
  left join public.daily_answers a on a.user_id = v_user and a.question_date = v_today - g.i;

  return jsonb_build_object('today', v_today, 'archive_start', v_start, 'days', v_list);
end;
$$;

