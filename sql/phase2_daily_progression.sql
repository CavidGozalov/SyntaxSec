-- Today's question without the correct answer, plus whether the caller answered it.
create or replace function public.get_daily_question()
returns jsonb
language plpgsql security definer set search_path = public, pg_temp
as $$
declare
  v_user  uuid := auth.uid();
  v_today date := public.daily_today();
begin
  if v_user is null then
    raise exception 'not_authenticated' using errcode = 'P0001';
  end if;
  perform public.daily_ensure_question(v_today);
  return public.daily_question_payload(v_user, v_today) || jsonb_build_object('is_today', true);
end;
$$;

-- Answer today's question (once). p_question_id is the id the browser is
-- showing: if Baku midnight passed in the meantime the call is rejected
-- instead of silently answering the next day's question.
create or replace function public.submit_daily_answer(p_choice integer, p_question_id integer default null)
returns jsonb
language plpgsql security definer set search_path = public, pg_temp
as $$
declare
  v_today date := public.daily_today();
  v_qid   integer;
begin
  if auth.uid() is null then
    raise exception 'not_authenticated' using errcode = 'P0001';
  end if;
  v_qid := public.daily_ensure_question(v_today);
  if p_question_id is not null and p_question_id <> v_qid then
    raise exception 'question_changed' using errcode = 'P0001';
  end if;
  return public.daily_submit(v_today, p_choice, false);
end;
$$;

-- A past question without its answer. Today, future dates and dates before
-- the archive start are rejected.
create or replace function public.get_past_question(p_date date)
returns jsonb
language plpgsql security definer set search_path = public, pg_temp
as $$
declare
  v_user  uuid := auth.uid();
  v_today date := public.daily_today();
begin
  if v_user is null then
    raise exception 'not_authenticated' using errcode = 'P0001';
  end if;
  if p_date is null then
    raise exception 'invalid_date' using errcode = 'P0001';
  end if;
  if p_date >= v_today then
    raise exception 'date_not_past' using errcode = 'P0001';
  end if;
  if p_date < (select archive_start from public.progression_settings limit 1) then
    raise exception 'date_out_of_range' using errcode = 'P0001';
  end if;
  perform public.daily_ensure_question(p_date);
  return public.daily_question_payload(v_user, p_date) || jsonb_build_object('is_today', false);
end;
$$;

