-- 6. ASSIGN QUESTIONS for the archive window and for today, so the
--    feature (and the archive) works straight away.
-- ---------------------------------------------------------------------
do $$
declare
  v_day date;
begin
  for v_day in
    select s.archive_start + g.i
    from public.progression_settings s,
         generate_series(0, greatest(public.daily_today() - s.archive_start, 0)) as g(i)
    order by 1
  loop
    perform public.daily_ensure_question(v_day);
  end loop;
end;
$$;

