--  Run it AFTER supabase-setup.sql and sql/phase1_account_basics.sql.
--  It is safe to run more than once.
--
--  What it adds:
--    Tables     questions, daily_questions, daily_answers, reward_items,
--               reward_rarity_weights, progression_settings, user_inventory,
--               user_streaks, streak_restores, titles, user_titles
--    Column     profiles.selected_title_id
--    Functions  (callable by signed-in users)
--               get_daily_question(), submit_daily_answer(choice, question id),
--               get_past_question(date), submit_past_answer(date, choice),
--               get_daily_archive(), get_daily_progress(),
--               restore_streak(date), set_selected_title(title id)
--               (internal helpers, not callable from the browser)
--               daily_today, daily_ensure_question, daily_question_payload,
--               daily_day_done, daily_streak_calc, daily_sync_streak,
--               daily_unlock_titles, daily_roll_item, daily_grant_item,
--               daily_progress, daily_submit
--
--  Rules that matter:
--    * Every "day" is a calendar date in Asia/Baku, computed here in the
--      database (daily_today()), never in the browser.
--    * questions.correct_index never leaves the database: the table has
--      row level security with no policy and no grant, and no function
--      returns the column.
--    * Users can only READ their own answers, streak, inventory, restores
--      and titles. Every write goes through the functions below.
--    * Nothing from Phase 1 is changed or dropped. profiles keeps its
--      column-level update grant (username, avatar_key), so the new
--      selected_title_id column can only be changed by set_selected_title().
--
--  To undo this script, run sql/phase2_rollback.sql.
-- =====================================================================

begin;

-- ---------------------------------------------------------------------
-- 1. TABLES
-- ---------------------------------------------------------------------

-- Question bank. correct_index is 0-based and is never sent to the client.
create table if not exists public.questions (
  id             integer generated by default as identity primary key,
  category       text not null default 'general',
  difficulty     text not null default 'easy' check (difficulty in ('easy', 'medium', 'hard')),
  prompt_en      text not null,
  prompt_az      text not null,
  choices_en     text[] not null,
  choices_az     text[] not null,
  correct_index  smallint not null,
  explanation_en text not null default '',
  explanation_az text not null default '',
  active         boolean not null default true,
  created_at     timestamptz not null default now(),
  constraint questions_choices_check check (
    array_length(choices_en, 1) between 2 and 6
    and array_length(choices_az, 1) = array_length(choices_en, 1)
    and correct_index >= 0
    and correct_index < array_length(choices_en, 1)
  )
);

-- Exactly one question per Baku date; the same one for everybody.
create table if not exists public.daily_questions (
  question_date date primary key,
  question_id   integer not null references public.questions (id) on delete restrict,
  created_at    timestamptz not null default now()
);
create index if not exists daily_questions_question_id_idx on public.daily_questions (question_id);

-- One answer per user per date. The primary key is the unique constraint
-- on (user_id, question_date) that makes a double answer impossible.
create table if not exists public.daily_answers (
  user_id       uuid not null references auth.users (id) on delete cascade,
  question_date date not null references public.daily_questions (question_date) on delete cascade,
  question_id   integer not null references public.questions (id) on delete restrict,
  choice_index  smallint not null check (choice_index >= 0),
  is_correct    boolean not null,
  is_archive    boolean not null default false,  -- true = answered later, from the archive
  answered_at   timestamptz not null default now(),
  primary key (user_id, question_date)
);

-- Collectible rewards.
create table if not exists public.reward_items (
  id      integer primary key,
  name_en text not null,
  name_az text not null,
  type    text not null default 'item' check (type in ('item')),
  rarity  text not null check (rarity in ('common', 'uncommon', 'rare', 'epic', 'legendary')),
  icon    text not null default '🎁',
  active  boolean not null default true
);

-- Drop chances, in percent. Edit the weights here; sort_order ranks the rarities.
create table if not exists public.reward_rarity_weights (
  rarity     text primary key check (rarity in ('common', 'uncommon', 'rare', 'epic', 'legendary')),
  weight     integer not null check (weight >= 0),
  sort_order smallint not null unique
);

-- All progression thresholds live in this single row.
create table if not exists public.progression_settings (
  id                    boolean primary key default true check (id),
  bonus_roll_streak     integer not null default 3 check (bonus_roll_streak >= 1),      -- streak that adds one extra item roll
  guarantee_streak      integer not null default 7 check (guarantee_streak >= 1),       -- streak that guarantees a minimum rarity
  guarantee_min_rarity  text not null default 'uncommon' references public.reward_rarity_weights (rarity),
  archive_reward_rarity text not null default 'common' references public.reward_rarity_weights (rarity),
  restores_per_month    integer not null default 3 check (restores_per_month >= 0),
  archive_start         date not null default ((now() at time zone 'Asia/Baku')::date - 7)  -- oldest date offered in the archive
);

create table if not exists public.user_inventory (
  id            bigint generated always as identity primary key,
  user_id       uuid not null references auth.users (id) on delete cascade,
  item_id       integer not null references public.reward_items (id) on delete cascade,
  obtained_at   timestamptz not null default now(),
  source        text not null default 'daily' check (source in ('daily', 'streak_bonus', 'archive')),
  question_date date
);
create index if not exists user_inventory_user_id_idx on public.user_inventory (user_id);

-- One row per user. restores_month is the first day of the Baku month the
-- restores_remaining count applies to.
create table if not exists public.user_streaks (
  user_id             uuid primary key references auth.users (id) on delete cascade,
  current_streak      integer not null default 0 check (current_streak >= 0),
  longest_streak      integer not null default 0 check (longest_streak >= 0),
  last_completed_date date,
  restores_remaining  integer not null default 0 check (restores_remaining >= 0),
  restores_month      date not null,
  updated_at          timestamptz not null default now()
);

-- A restored day counts as completed for the streak, but gives no item.
create table if not exists public.streak_restores (
  user_id       uuid not null references auth.users (id) on delete cascade,
  restored_date date not null,   -- the missed day that was restored
  used_on       date not null,   -- the Baku date the restore was spent
  created_at    timestamptz not null default now(),
  primary key (user_id, restored_date)
);

-- requirement_type: 'streak'    → longest streak >= requirement_value
--                   'completed' → questions answered (daily + archive) >= requirement_value
--                   'items'     → items in the inventory >= requirement_value
create table if not exists public.titles (
  id                integer primary key,
  name_en           text not null,
  name_az           text not null,
  requirement_type  text not null check (requirement_type in ('streak', 'completed', 'items')),
  requirement_value integer not null default 0 check (requirement_value >= 0),
  is_default        boolean not null default false,  -- selected automatically the first time it unlocks
  sort_order        integer not null default 0
);

create table if not exists public.user_titles (
  user_id     uuid not null references auth.users (id) on delete cascade,
  title_id    integer not null references public.titles (id) on delete cascade,
  unlocked_at timestamptz not null default now(),
  primary key (user_id, title_id)
);

-- The title shown next to the username. Not covered by the Phase 1 column
-- grant, so the browser cannot update it directly.
alter table public.profiles
  add column if not exists selected_title_id integer
  constraint profiles_selected_title_id_fkey references public.titles (id) on delete set null;

