-- Today's calendar date in Baku (UTC+4, no daylight saving time).
create or replace function public.daily_today()
returns date
language sql stable security definer set search_path = public, pg_temp
as $$
  select (now() at time zone 'Asia/Baku')::date;
$$;

-- Returns the question assigned to p_date, assigning one first if needed.
-- Picks an active question that was not used within a week of p_date when
-- possible, then the least-used one; the md5 makes the order look random
-- but stable. "on conflict do nothing" keeps one row per date under races.
create or replace function public.daily_ensure_question(p_date date)
returns integer
language plpgsql security definer set search_path = public, pg_temp
as $$
declare
  v_id integer;
begin
  select question_id into v_id from public.daily_questions where question_date = p_date;
  if v_id is not null then
    return v_id;
  end if;

  select q.id into v_id
  from public.questions q
  where q.active
  order by
    (exists (select 1 from public.daily_questions d
             where d.question_id = q.id and d.question_date between p_date - 7 and p_date + 7))::int,
    (select count(*) from public.daily_questions d where d.question_id = q.id),
    md5(p_date::text || ':' || q.id::text)
  limit 1;

  if v_id is null then
    raise exception 'no_questions' using errcode = 'P0001';
  end if;

  insert into public.daily_questions (question_date, question_id)
  values (p_date, v_id)
  on conflict (question_date) do nothing;

  select question_id into v_id from public.daily_questions where question_date = p_date;
  return v_id;
end;
$$;

-- The question for p_date as JSON, WITHOUT correct_index. The explanation
-- and the user's own result are included only once that user has answered.
create or replace function public.daily_question_payload(p_user uuid, p_date date)
returns jsonb
language sql stable security definer set search_path = public, pg_temp
as $$
  select jsonb_build_object(
    'date', d.question_date,
    'question', jsonb_build_object(
      'id', q.id,
      'category', q.category,
      'difficulty', q.difficulty,
      'prompt_en', q.prompt_en,
      'prompt_az', q.prompt_az,
      'choices_en', to_jsonb(q.choices_en),
      'choices_az', to_jsonb(q.choices_az)
    ),
    'answered', a.user_id is not null,
    'answer', case when a.user_id is null then null else jsonb_build_object(
      'choice_index', a.choice_index,
      'is_correct', a.is_correct,
      'is_archive', a.is_archive,
      'explanation_en', q.explanation_en,
      'explanation_az', q.explanation_az
    ) end
  )
  from public.daily_questions d
  join public.questions q on q.id = d.question_id
  left join public.daily_answers a on a.question_date = d.question_date and a.user_id = p_user
  where d.question_date = p_date;
$$;

-- Does p_date count towards the streak? (answered on the day itself, or restored)
create or replace function public.daily_day_done(p_user uuid, p_date date)
returns boolean
language sql stable security definer set search_path = public, pg_temp
as $$
  select exists (select 1 from public.daily_answers
                 where user_id = p_user and question_date = p_date and not is_archive)
      or exists (select 1 from public.streak_restores
                 where user_id = p_user and restored_date = p_date);
$$;

-- Streak numbers computed from the stored days (gaps-and-islands).
-- current_streak is the run of consecutive days ending today or yesterday,
-- otherwise 0. Right and wrong answers both count.
create or replace function public.daily_streak_calc(
  p_user uuid, p_today date,
  out current_streak integer, out longest_streak integer, out last_completed date
)
language sql stable security definer set search_path = public, pg_temp
as $$
  with days as (
    select question_date as d from public.daily_answers where user_id = p_user and not is_archive
    union
    select restored_date from public.streak_restores where user_id = p_user
  ), grouped as (
    select d, d - (row_number() over (order by d))::integer as g from days
  ), islands as (
    select max(d) as last_day, count(*)::integer as len from grouped group by g
  )
  select
    coalesce((select len from islands where last_day >= p_today - 1 order by last_day desc limit 1), 0),
    coalesce((select max(len) from islands), 0),
    (select max(last_day) from islands);
$$;

-- Writes the computed streak into user_streaks (creating the row if needed)
-- and resets the restore count when a new Baku month has started.
-- The upsert locks the user's row until the transaction ends.
create or replace function public.daily_sync_streak(p_user uuid)
returns public.user_streaks
language plpgsql security definer set search_path = public, pg_temp
as $$
declare
  v_today   date := public.daily_today();
  v_month   date := date_trunc('month', v_today)::date;
  v_quota   integer;
  v_current integer;
  v_longest integer;
  v_last    date;
  v_row     public.user_streaks;
begin
  select restores_per_month into v_quota from public.progression_settings limit 1;
  v_quota := coalesce(v_quota, 0);

  select c.current_streak, c.longest_streak, c.last_completed
    into v_current, v_longest, v_last
  from public.daily_streak_calc(p_user, v_today) c;

  insert into public.user_streaks as us
    (user_id, current_streak, longest_streak, last_completed_date, restores_remaining, restores_month)
  values (p_user, v_current, v_longest, v_last, v_quota, v_month)
  on conflict (user_id) do update set
    current_streak      = excluded.current_streak,
    longest_streak      = greatest(us.longest_streak, excluded.longest_streak),
    last_completed_date = excluded.last_completed_date,
    restores_remaining  = case when us.restores_month = excluded.restores_month
                               then us.restores_remaining else excluded.restores_remaining end,
    restores_month      = excluded.restores_month,
    updated_at          = now()
  returning us.* into v_row;

  return v_row;
end;
$$;

-- Unlocks every title whose requirement is now met. Returns the newly
-- unlocked titles. The default title is selected the first time it unlocks.
create or replace function public.daily_unlock_titles(p_user uuid)
returns jsonb
language plpgsql security definer set search_path = public, pg_temp
as $$
declare
  v_longest integer;
  v_done    integer;
  v_items   integer;
  v_new     jsonb;
begin
  select longest_streak into v_longest from public.user_streaks where user_id = p_user;
  select count(*) into v_done from public.daily_answers where user_id = p_user;
  select count(*) into v_items from public.user_inventory where user_id = p_user;

  with ins as (
    insert into public.user_titles (user_id, title_id)
    select p_user, t.id
    from public.titles t
    where (t.requirement_type = 'streak'    and coalesce(v_longest, 0) >= t.requirement_value)
       or (t.requirement_type = 'completed' and v_done >= t.requirement_value)
       or (t.requirement_type = 'items'     and v_items >= t.requirement_value)
    on conflict (user_id, title_id) do nothing
    returning title_id
  )
  select coalesce(jsonb_agg(jsonb_build_object(
           'id', t.id, 'name_en', t.name_en, 'name_az', t.name_az, 'is_default', t.is_default
         ) order by t.sort_order), '[]'::jsonb)
    into v_new
  from ins join public.titles t on t.id = ins.title_id;

  update public.profiles p
     set selected_title_id = (e.value ->> 'id')::integer
    from jsonb_array_elements(v_new) e
   where p.id = p_user
     and p.selected_title_id is null
     and (e.value ->> 'is_default')::boolean;

  return v_new;
end;
$$;

-- Weighted random roll, done entirely in the database.
--   p_min_rarity  : lowest rarity allowed (for the streak guarantee)
--   p_only_rarity : if set, only this rarity (for archive rewards)
-- A rarity is picked by weight (key = -ln(u) / weight, smallest wins),
-- then a random active item of that rarity.
create or replace function public.daily_roll_item(p_min_rarity text default 'common', p_only_rarity text default null)
returns integer
language plpgsql volatile security definer set search_path = public, pg_temp
as $$
declare
  v_min    smallint;
  v_rarity text;
  v_item   integer;
begin
  select sort_order into v_min from public.reward_rarity_weights where rarity = p_min_rarity;

  select w.rarity into v_rarity
  from public.reward_rarity_weights w
  where w.weight > 0
    and w.sort_order >= coalesce(v_min, 0)
    and (p_only_rarity is null or w.rarity = p_only_rarity)
    and exists (select 1 from public.reward_items i where i.rarity = w.rarity and i.active)
  order by -ln(1.0 - random()) / w.weight
  limit 1;

  select i.id into v_item
  from public.reward_items i
  where i.active and (v_rarity is null or i.rarity = v_rarity)
  order by random()
  limit 1;

  return v_item;
end;
$$;

-- Rolls one item, adds it to the inventory and returns it as JSON (null if there are no items).
create or replace function public.daily_grant_item(
  p_user uuid, p_date date, p_source text,
  p_min_rarity text default 'common', p_only_rarity text default null
)
returns jsonb
language plpgsql volatile security definer set search_path = public, pg_temp
as $$
declare
  v_item integer;
  v_json jsonb;
begin
  v_item := public.daily_roll_item(p_min_rarity, p_only_rarity);
  if v_item is null then
    return null;
  end if;

  insert into public.user_inventory (user_id, item_id, source, question_date)
  values (p_user, v_item, p_source, p_date);

  select jsonb_build_object(
           'id', i.id, 'name_en', i.name_en, 'name_az', i.name_az,
           'type', i.type, 'rarity', i.rarity, 'icon', i.icon, 'source', p_source)
    into v_json
  from public.reward_items i where i.id = v_item;

  return v_json;
end;
$$;

-- Everything the dashboard, the daily page and the profile need, in one object.
create or replace function public.daily_progress(p_user uuid)
returns jsonb
language plpgsql security definer set search_path = public, pg_temp
as $$
declare
  v_today date := public.daily_today();
  s       public.progression_settings;
  r       public.user_streaks;
  v_new   jsonb;
  v_can   boolean;
begin
  select * into s from public.progression_settings limit 1;
  r := public.daily_sync_streak(p_user);
  v_new := public.daily_unlock_titles(p_user);

  -- A restore is possible only for yesterday, only if yesterday was missed,
  -- and only if it reconnects to a day that was completed the day before.
  v_can := r.restores_remaining > 0
       and not public.daily_day_done(p_user, v_today - 1)
       and public.daily_day_done(p_user, v_today - 2);

  return jsonb_build_object(
    'today', v_today,
    'current_streak', r.current_streak,
    'longest_streak', r.longest_streak,
    'last_completed_date', r.last_completed_date,
    'restores_remaining', r.restores_remaining,
    'restores_per_month', s.restores_per_month,
    'restores_month', r.restores_month,
    'can_restore', v_can,
    'restore_date', v_today - 1,
    'answered_today', exists (select 1 from public.daily_answers a
                              where a.user_id = p_user and a.question_date = v_today),
    'completed_total', (select count(*) from public.daily_answers a where a.user_id = p_user),
    'items_total', (select count(*) from public.user_inventory i where i.user_id = p_user),
    'bonus_roll_streak', s.bonus_roll_streak,
    'guarantee_streak', s.guarantee_streak,
    'guarantee_min_rarity', s.guarantee_min_rarity,
    'archive_start', s.archive_start,
    'selected_title_id', (select p.selected_title_id from public.profiles p where p.id = p_user),
    'titles', (select coalesce(jsonb_agg(jsonb_build_object(
                 'id', t.id, 'name_en', t.name_en, 'name_az', t.name_az,
                 'requirement_type', t.requirement_type, 'requirement_value', t.requirement_value,
                 'unlocked', ut.user_id is not null
               ) order by t.sort_order), '[]'::jsonb)
               from public.titles t
               left join public.user_titles ut on ut.title_id = t.id and ut.user_id = p_user),
    'new_titles', v_new
  );
end;
$$;

-- Records one answer and hands out the rewards. Shared by today's question
-- (p_archive = false) and the archive (p_archive = true).
create or replace function public.daily_submit(p_date date, p_choice integer, p_archive boolean)
returns jsonb
language plpgsql security definer set search_path = public, pg_temp
as $$
declare
  v_user    uuid := auth.uid();
  s         public.progression_settings;
  v_q       public.questions;
  r         public.user_streaks;
  v_correct boolean;
  v_items   jsonb := '[]'::jsonb;
  v_item    jsonb;
begin
  if v_user is null then
    raise exception 'not_authenticated' using errcode = 'P0001';
  end if;

  select q.* into v_q
  from public.daily_questions d join public.questions q on q.id = d.question_id
  where d.question_date = p_date;
  if v_q.id is null then
    raise exception 'no_questions' using errcode = 'P0001';
  end if;

  if p_choice is null or p_choice < 0 or p_choice >= array_length(v_q.choices_en, 1) then
    raise exception 'invalid_choice' using errcode = 'P0001';
  end if;

  if exists (select 1 from public.daily_answers where user_id = v_user and question_date = p_date) then
    raise exception 'already_answered' using errcode = 'P0001';
  end if;

  v_correct := (p_choice = v_q.correct_index);

  -- The answer is stored BEFORE any reward. If two requests race, the
  -- primary key (user_id, question_date) lets only one of them through.
  begin
    insert into public.daily_answers (user_id, question_date, question_id, choice_index, is_correct, is_archive)
    values (v_user, p_date, v_q.id, p_choice, v_correct, p_archive);
  exception when unique_violation then
    raise exception 'already_answered' using errcode = 'P0001';
  end;

  select * into s from public.progression_settings limit 1;
  r := public.daily_sync_streak(v_user);

  if p_archive then
    -- Reduced reward: no streak change (archive days are ignored by the
    -- streak calculation) and one item of the configured rarity only.
    v_item := public.daily_grant_item(v_user, p_date, 'archive', 'common', s.archive_reward_rarity);
    if v_item is not null then v_items := v_items || v_item; end if;
  else
    v_item := public.daily_grant_item(
      v_user, p_date, 'daily',
      case when r.current_streak >= s.guarantee_streak then s.guarantee_min_rarity else 'common' end,
      null);
    if v_item is not null then v_items := v_items || v_item; end if;

    if r.current_streak >= s.bonus_roll_streak then
      v_item := public.daily_grant_item(v_user, p_date, 'streak_bonus', 'common', null);
      if v_item is not null then v_items := v_items || v_item; end if;
    end if;
  end if;

  return jsonb_build_object(
    'date', p_date,
    'is_archive', p_archive,
    'choice_index', p_choice,
    'correct', v_correct,
    'explanation_en', v_q.explanation_en,
    'explanation_az', v_q.explanation_az,
    'items', v_items,
    'progress', public.daily_progress(v_user)
  );
end;
$$;

