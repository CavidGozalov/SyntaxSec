-- Restore yesterday. Only yesterday can be restored, only if it was missed,
-- only if the day before it was completed, and only while restores remain
-- for the current Baku month. Gives no item.
create or replace function public.restore_streak(p_date date default null)
returns jsonb
language plpgsql security definer set search_path = public, pg_temp
as $$
declare
  v_user      uuid := auth.uid();
  v_today     date := public.daily_today();
  v_yesterday date := public.daily_today() - 1;
  r           public.user_streaks;
begin
  if v_user is null then
    raise exception 'not_authenticated' using errcode = 'P0001';
  end if;
  if p_date is not null and p_date <> v_yesterday then
    raise exception 'restore_only_yesterday' using errcode = 'P0001';
  end if;

  -- Creates/locks the user's row and applies the monthly reset first.
  r := public.daily_sync_streak(v_user);

  if public.daily_day_done(v_user, v_yesterday) then
    raise exception 'restore_not_needed' using errcode = 'P0001';
  end if;
  if not public.daily_day_done(v_user, v_yesterday - 1) then
    raise exception 'restore_not_consecutive' using errcode = 'P0001';
  end if;
  if r.restores_remaining <= 0 then
    raise exception 'restore_none_left' using errcode = 'P0001';
  end if;

  begin
    insert into public.streak_restores (user_id, restored_date, used_on)
    values (v_user, v_yesterday, v_today);
  exception when unique_violation then
    raise exception 'restore_not_needed' using errcode = 'P0001';
  end;

  update public.user_streaks
     set restores_remaining = restores_remaining - 1
   where user_id = v_user;

  return public.daily_progress(v_user) || jsonb_build_object('restored_date', v_yesterday);
end;
$$;

-- Choose the title shown on the profile. NULL shows no title. A title the
-- caller has not unlocked (or that does not exist) is rejected.
create or replace function public.set_selected_title(p_title_id integer)
returns jsonb
language plpgsql security definer set search_path = public, pg_temp
as $$
declare
  v_user uuid := auth.uid();
begin
  if v_user is null then
    raise exception 'not_authenticated' using errcode = 'P0001';
  end if;
  if p_title_id is not null and not exists (
    select 1 from public.user_titles where user_id = v_user and title_id = p_title_id
  ) then
    raise exception 'title_locked' using errcode = 'P0001';
  end if;

  update public.profiles set selected_title_id = p_title_id where id = v_user;
  if not found then
    raise exception 'profile_not_found' using errcode = 'P0001';
  end if;

  return jsonb_build_object('selected_title_id', p_title_id);
end;
$$;

